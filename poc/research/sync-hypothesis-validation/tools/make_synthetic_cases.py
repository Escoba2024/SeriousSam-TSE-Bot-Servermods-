def server_log(sync_bads: int = 10, kick: bool = True, jump: bool = False,
               first_tick: float = 83.40, step: float = 1.0) -> str:
    lines = [
        "SeriousSam Dedicated Server",
        "Level 'KarnakDemo' started",
        "Client '127.0.0.1' connected",
    ]
    tick = first_tick
    counter = 0
    for index in range(sync_bads):
        counter += 2 if (jump and index == 3) else 1
        lines.append("SYNCBAD: Client '127.0.0.1', Sequence %d Tick %.2f - bad %d"
                     % (1689 + index * 20, tick, counter))
        tick += step
    if kick:
        lines.append("Client '127.0.0.1' ordered to disconnect: Too many bad syncs")
        lines.append("Disconnected: Too many bad syncs")
    return "\n".join(lines) + "\n"


def dump_text(level: str, sequence: int, tick: float, fields: Dict[str, str],
              crc: int) -> str:
    lines = ["CRC: 0x%08X" % crc, "Level: %s" % level,
             "Sequence: %d" % sequence, "Tick: %.2f" % tick]
    for name, value in fields.items():
        lines.append("%s = %s" % (name, value))
    return "\n".join(lines) + "\n"


