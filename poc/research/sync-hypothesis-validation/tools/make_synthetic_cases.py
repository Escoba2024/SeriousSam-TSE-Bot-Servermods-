#!/usr/bin/env python3
"""Deterministic synthetic fixtures for the sync-hypothesis toolchain.

Every artifact is generated from a fixed seed and a fixed script; no real log,
dump, binary or game file is needed or read. Two safety properties matter:

* every bundle written here carries ``GENERATED_FIXTURE.txt``; the bundle audit
  turns that marker into ``SIMULATED_NEVER_NATIVE``, so generated data can never
  be mistaken for a native Retail run;
* the fixtures cover the *negative* controls as well: aligned dumps that are
  identical, an action trace whose only difference lies outside the checksum
  scope, a cadence-clean telemetry file, and a manifest with a lowered
  ``ser_iKickOnSyncBad``.

Usage::

    python3 tools/make_synthetic_cases.py --out /tmp/syncval-fixtures

Exit codes: 0 ok, 2 usage error.
"""

