FIXTURE_MARKER = """SYNTHETIC FIXTURE - NOT NATIVE EVIDENCE
Generated by poc/research/sync-hypothesis-validation/tools/make_synthetic_cases.py.
No real Serious Sam log, dump, binary or game data is contained in this tree.
Any audit of this bundle must refuse it as native evidence.
"""

TELEMETRY_COLUMNS = (
    "t_ms,ticks,actions,frames,renderskip,renderdraw,lp,gameon,enabled,"
    "disabled,gameoff,nolocal,noentity,lock_ms_max,lock_ms_last,tick_ms_max,"
    "tick_ms_avg,cpu_user_ms,cpu_kernel_ms,stall_s,reason"
)

# Hypothetical layout used ONLY to exercise the probe. The real 1.07 offsets
# must come from the SDK header; these numbers are not a 1.07 claim.
LAYOUT_FIELDS = [
    {"name": "pa_vTranslation", "offset": 0, "size": 12},
    {"name": "pa_aRotation", "offset": 12, "size": 12},
    {"name": "pa_aViewRotation", "offset": 24, "size": 12},
    {"name": "pa_ulButtons", "offset": 36, "size": 4},
]
LAYOUT_CALLS = [{"offset": 4, "length": 4}, {"offset": 16, "length": 4}]
STRUCT_SIZE = 40


# ---------------------------------------------------------------------------
# action traces
# ---------------------------------------------------------------------------

def action_bytes(tick: int, speed: float, yaw_rate: float) -> bytearray:
    """Build a 40-byte action image for one tick (conventions: forward = -Z)."""
    dt = 1.0 / 20.0
    heading = f32(yaw_rate * dt * tick)
    blob = bytearray(STRUCT_SIZE)
    struct.pack_into("<f", blob, 0, f32(0.0))            # translation x
    struct.pack_into("<f", blob, 4, f32(0.0))            # translation y
    struct.pack_into("<f", blob, 8, f32(-speed))         # translation z (forward)
    struct.pack_into("<f", blob, 12, f32(0.0))           # rotation x
    struct.pack_into("<f", blob, 16, heading)            # rotation y (accumulated)
    struct.pack_into("<f", blob, 20, f32(0.0))           # rotation z
    struct.pack_into("<f", blob, 24, f32(0.0))           # view rotation x
    struct.pack_into("<f", blob, 28, f32(0.0))           # view rotation y
    struct.pack_into("<f", blob, 32, f32(0.0))           # view rotation z
    struct.pack_into("<I", blob, 36, 0)                  # buttons
    return blob


def write_trace(path: Path, ticks: int, mutate=None, label: str = "synthetic") -> None:
    lines = ["#syncval-action-trace,rev=1", "#source,%s" % label,
             "#tick,slot,bytes_hex"]
    for tick in range(ticks):
        blob = action_bytes(tick, speed=15.0, yaw_rate=45.7)
        if mutate is not None:
            mutate(tick, blob)
        lines.append("%d,0,%s" % (tick, blob.hex()))
    write_text(path, "\n".join(lines) + "\n")


def _flip_lsb(blob: bytearray, offset: int) -> None:
    blob[offset] = (blob[offset] ^ 0x01) & 0xFF


# ---------------------------------------------------------------------------
# telemetry
# ---------------------------------------------------------------------------

def write_telemetry(path: Path, script, seconds: int = 60, lp: int = 1,
                    header: bool = True) -> None:
    """script(second) -> (d_ticks, d_actions, gameon, enabled)"""
    lines: List[str] = []
    if header:
        lines.append("#bot-telemetry,rev=1")
        lines.append("#build,tag=synthetic-fixture,built=2026-10-25")
        lines.append("#columns," + TELEMETRY_COLUMNS)
    ticks = 0
    actions = 0
    frames = 0
    for second in range(seconds):
        d_ticks, d_actions, gameon, enabled = script(second)
        ticks += d_ticks
        actions += d_actions
        frames += 60
        row = {
            "t_ms": second * 1000,
            "ticks": ticks,
            "actions": actions,
            "frames": frames,
            "renderskip": 0,
            "renderdraw": frames,
            "lp": lp,
            "gameon": gameon,
            "enabled": enabled,
            "disabled": 0 if enabled else 1,
            "gameoff": 0 if gameon else 1,
            "nolocal": 0,
            "noentity": 0,
            "lock_ms_max": 1,
            "lock_ms_last": 0,
            "tick_ms_max": 3,
            "tick_ms_avg": 1,
            "cpu_user_ms": 400,
            "cpu_kernel_ms": 40,
            "stall_s": 0,
            "reason": 0 if (enabled and gameon) else 2,
        }
        lines.append(",".join(str(row[c]) for c in TELEMETRY_COLUMNS.split(",")))
    write_text(path, "\n".join(lines) + "\n")


