def generate(out: Path) -> Dict[str, str]:
    out.mkdir(parents=True, exist_ok=True)
    written: Dict[str, str] = {}

    # --- layout hypotheses -------------------------------------------------
    layout_base = {
        "struct_size": STRUCT_SIZE,
        "fields": LAYOUT_FIELDS,
        "checksum_calls": LAYOUT_CALLS,
    }
    verified = dict(layout_base)
    verified.update({
        "status": "VERIFIED_107",
        "source": "SYNTHETIC TEST LAYOUT - NOT 1.07 OFFSETS (fixture only)",
    })
    write_text(out / "layout_verified.json", json.dumps(verified, indent=2) + "\n")
    unverified = dict(layout_base)
    unverified.update({
        "status": "UNVERIFIED",
        "source": "SYNTHETIC TEST LAYOUT - hypothesis only",
    })
    write_text(out / "layout_unverified.json", json.dumps(unverified, indent=2) + "\n")
    written["layout_verified"] = "layout_verified.json"
    written["layout_unverified"] = "layout_unverified.json"

    # --- action traces -----------------------------------------------------
    write_trace(out / "actions_client.csv", ticks=201)
    write_trace(out / "actions_server_identical.csv", ticks=201)
    write_trace(out / "actions_server_visible_diff.csv", ticks=201,
                mutate=lambda tick, blob: _flip_lsb(blob, 16) if tick == 137 else None,
                label="synthetic-visible-diff")
    write_trace(out / "actions_server_outside_diff.csv", ticks=201,
                mutate=lambda tick, blob: _flip_lsb(blob, 24) if tick >= 90 else None,
                label="synthetic-outside-diff")
    write_trace(out / "actions_server_truncated.csv", ticks=100,
                label="synthetic-truncated")
    for name in ("actions_client", "actions_server_identical",
                 "actions_server_visible_diff", "actions_server_outside_diff",
                 "actions_server_truncated"):
        written[name] = "%s.csv" % name

    # --- telemetry ---------------------------------------------------------
    def ok(second):            # noqa: ARG001
        return 20, 20, 1, 1

    def starved(second):
        return (8 if 20 <= second < 30 else 20), (8 if 20 <= second < 30 else 20), 1, 1

    def dead(second):
        return (0 if 40 <= second < 43 else 20), (0 if 40 <= second < 43 else 20), 1, 1

    def coalesced(second):
        return 20, (40 if 25 <= second < 30 else 20), 1, 1

    def inactive(second):      # noqa: ARG001
        return 0, 0, 0, 0

    write_telemetry(out / "telemetry_ok.csv", ok)
    write_telemetry(out / "telemetry_starved.csv", starved)
    write_telemetry(out / "telemetry_dead.csv", dead)
    write_telemetry(out / "telemetry_coalesced.csv", coalesced)
    write_telemetry(out / "telemetry_inactive.csv", inactive)
    write_telemetry(out / "telemetry_malformed.csv", ok, seconds=5, header=False)
    for name in ("telemetry_ok", "telemetry_starved", "telemetry_dead",
                 "telemetry_coalesced", "telemetry_inactive", "telemetry_malformed"):
        written[name] = "%s.csv" % name

    # --- server logs -------------------------------------------------------
    write_text(out / "server_syncbad_burst.log", server_log())
    write_text(out / "server_syncbad_jump.log", server_log(jump=True))
    write_text(out / "server_endless_syncbad.log", server_log(sync_bads=40, kick=False))
    written["server_syncbad_burst"] = "server_syncbad_burst.log"
    written["server_syncbad_jump"] = "server_syncbad_jump.log"
    written["server_endless_syncbad"] = "server_endless_syncbad.log"

    # --- bundles -----------------------------------------------------------
    _write_bundle(out / "bundle_simulated", simulated=True, with_dumps=True)
    _write_bundle(out / "bundle_incomplete", simulated=False, with_dumps=False)
    _write_bundle(out / "bundle_lowered_kick", simulated=False, with_dumps=True,
                  kick_limit=0)
    for name in ("bundle_simulated", "bundle_incomplete", "bundle_lowered_kick"):
        written[name] = "%s/manifest.json" % name

    # --- observation files -------------------------------------------------
    model_obs = {
        "observations": [
            {"id": "cadence.divergence_windows", "value": 0,
             "evidence_class": "model", "source": "synthetic"},
            {"id": "cadence.tick_rate_ratio", "value": 1.0,
             "evidence_class": "model", "source": "synthetic"},
            {"id": "cadence.action_fidelity", "value": 1.0,
             "evidence_class": "model", "source": "synthetic"},
        ]
    }
    write_text(out / "observations_model.json", json.dumps(model_obs, indent=2) + "\n")
    written["observations_model"] = "observations_model.json"

    return written


def _write_bundle(bundle: Path, simulated: bool, with_dumps: bool,
                  kick_limit: int = 10) -> None:
    import hashlib
    bundle.mkdir(parents=True, exist_ok=True)
    write_text(bundle / "GENERATED_FIXTURE.txt", FIXTURE_MARKER)
    log_text = server_log()
    write_text(bundle / "server.log", log_text)
    write_text(bundle / "client.log",
               "SeriousSam TSE client\nDisconnected: Too many bad syncs\n")
    write_telemetry(bundle / "BotTelemetry.csv",
                    lambda second: (20, 20, 1, 1), seconds=30)

    dumps = []
    if with_dumps:
        (bundle / "dumps" / "server").mkdir(parents=True, exist_ok=True)
        (bundle / "dumps" / "client").mkdir(parents=True, exist_ok=True)
        for sequence in (400, 420):
            tick = 100.0 + sequence / 20.0
            base_fields = {
                "PlayerActions": "0x00000000",
                "PlayerEntitys": "placement=1.0,2.0,3.0;health=100",
                "Pause": "0",
                "SessionTime": "%.2f" % tick,
            }
            server_fields = dict(base_fields)
            client_fields = dict(base_fields)
            if sequence == 420:
                client_fields["PlayerEntitys"] = "placement=1.0,2.0,3.0625;health=100"
            write_text(bundle / "dumps" / "server" / ("s%d.txt" % sequence),
                       dump_text("KarnakDemo", sequence, tick, server_fields, 0x11110000))
            write_text(bundle / "dumps" / "client" / ("c%d.txt" % sequence),
                       dump_text("KarnakDemo", sequence, tick, client_fields, 0x11110001))
            dumps.append("dumps/server/s%d.txt" % sequence)

    def digest(name: str) -> str:
        return hashlib.sha256((bundle / name).read_bytes()).hexdigest().upper()

    shared = {component: digest(component) for component in ()}
    component_hashes = {
        "exe_sha256": hashlib.sha256(b"synthetic-exe").hexdigest().upper(),
        "engine_sha256": hashlib.sha256(b"synthetic-engine").hexdigest().upper(),
        "entities_sha256": hashlib.sha256(b"synthetic-entities").hexdigest().upper(),
    }
    manifest = {
        "bundle_id": "syncval-fixture-%s" % bundle.name,
        "simulated": simulated,
        "run": {
            "id": "fixture-run",
            "date_utc": "2026-10-25T00:00:00Z",
            "operator": "SYNTHETIC-FIXTURE",
            "platform": "fixture",
            "tick_hz": 20,
            "map": "KarnakDemo",
            "bots": 1,
            "clients": 1,
        },
        "config": {
            "cli_bDumpSync": 1,
            "ser_bReportSyncBad": 1,
            "ser_iKickOnSyncBad": kick_limit,
            "frida_or_debugger_attached": False,
        },
        "processes": {
            "server": dict(component_hashes, network_version="1.07"),
            "clients": [dict(component_hashes,
                             name="botclient-1",
                             gamemp_sha256=hashlib.sha256(b"synthetic-gamemp")
                             .hexdigest().upper(),
                             gamemp_candidate="synthetic")],
        },
        "artifacts": {
            "server_log": {"path": "server.log", "sha256": digest("server.log")},
            "client_logs": [{"path": "client.log", "sha256": digest("client.log")}],
            "telemetry": [{"path": "BotTelemetry.csv",
                           "sha256": digest("BotTelemetry.csv")}],
            "server_dumps": dumps,
            "client_dumps": [path.replace("server/", "client/").replace("s4", "c4")
                             for path in dumps],
        },
    }
    _ = shared
    write_text(bundle / "manifest.json",
               json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True)
    parser.add_argument("--seed", type=int, default=20261025)
    args = parser.parse_args()

    require(args.out, "--out is required")
    _ = Lcg(args.seed)          # keep the seed surface stable for future use
    written = generate(Path(args.out))
    print(json.dumps({"written": written, "count": len(written),
                      "note": "synthetic fixtures only - never native evidence"},
                     indent=2))
    return EXIT_OK


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SyncValError as exc:
        print("error: %s" % exc, file=sys.stderr)
        raise SystemExit(EXIT_USAGE)
